import { NextRequest, NextResponse } from 'next/server';
import { getAuthContextFromRequest, assertAuthorized } from '@/lib/auth/session';
import { memoryStore } from '@/lib/db/memory-store';

export async function POST(
  req: NextRequest,
  { params }: { params: { id: string } }
) {
  try {
    const auth = await getAuthContextFromRequest(req);
    const requestId = params.id;
    const body = await req.json().catch(() => ({}));

    // 1. Fetch maintenance request
    const request = await memoryStore.getMaintenanceRequest(auth.organizationId, requestId);
    if (!request) {
      return NextResponse.json(
        { success: false, error: 'Maintenance request not found or unauthorized.' },
        { status: 404 }
      );
    }
    assertAuthorized(auth, request.organization_id, 'maintenance request');

    // 2. Prevent duplicate work orders (idempotency check)
    const existingWorkOrders = await memoryStore.getWorkOrders(auth.organizationId);
    const alreadyCreated = existingWorkOrders.find(w => w.request_id === requestId);
    if (alreadyCreated) {
      return NextResponse.json({
        success: true,
        message: 'Work order already exists for this request (idempotent return).',
        data: alreadyCreated,
      });
    }

    // 3. Prepare work order details
    const triage = request.ai_triage;
    const recommendedContractorId = body.contractor_id || triage?.recommended_contractor?.contractor_id;
    const contractorCompany = triage?.recommended_contractor?.company || 'Internal Facilities Staff';

    const workDescription = body.description || (
      triage
        ? `Scope of Work: ${triage.issue_summary}. Recommended Actions: ${triage.recommended_actions.join('; ')}. Safety Considerations: ${triage.safety_flags.join(', ') || 'Standard precautions'}.`
        : request.description
    );

    const newWorkOrder = await memoryStore.createWorkOrder({
      organization_id: auth.organizationId,
      request_id: requestId,
      contractor_id: recommendedContractorId,
      issue_summary: triage?.issue_summary || request.description.slice(0, 80),
      description: workDescription,
      priority: triage?.urgency || request.urgency,
      status: 'Awaiting Approval', // Human must review and approve!
      assigned_manager: `${auth.userName} (${auth.role})`,
      approval_history: [],
      simulated_actions: [
        `Draft generated by AI Triage Agent for Unit ${request.unit_number}`,
        `Proposed contractor assignment: ${contractorCompany} (pending manager approval)`,
      ],
    });

    return NextResponse.json({ success: true, data: newWorkOrder }, { status: 201 });
  } catch (error: unknown) {
    const err = error as { status?: number; message?: string };
    return NextResponse.json(
      { success: false, error: err.message || 'Failed to create work order' },
      { status: err.status || 500 }
    );
  }
}
